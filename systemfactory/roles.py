"""Specialised roles. Each role is a function `run(ctx) -> dict` with an explicit tool/permission policy.

All roles here are deterministic (rule-based / template-based / search-based). They are labelled as
such in their outputs so nothing is presented as LLM work. A future LLM provider would implement the
same signatures and the same permission policies.
"""
from __future__ import annotations

import doctest
import re
import time
from pathlib import Path

from . import repair
from .context import BlockedError, PermanentError, StepContext, TransientError
from .sandbox import GIT_LOCK, Workspace

# Declared permissions per role; shown on the dashboard and enforced by Workspace allow-lists.
ROLE_POLICIES = {
    "triage": {"reads": ["issue", "repo file list"], "writes": [], "commands": []},
    "requirements": {"reads": ["issue", "triage"], "writes": [], "commands": []},
    "architecture": {"reads": ["issue", "prd", "repo file list"], "writes": [], "commands": []},
    "infra": {"reads": ["repo"], "writes": ["data/worktrees/wf-<id>"], "commands": ["git worktree"]},
    "qa": {"reads": ["worktree"], "writes": ["tests/test_issue_*.py"], "commands": ["python -m pytest", "git commit"]},
    "coding": {"reads": ["worktree"], "writes": ["<plan.target_files only>"],
               "commands": ["python <repro test>", "python -m pytest", "git commit"]},
    "security": {"reads": ["diff"], "writes": [], "commands": ["git diff"]},
    "review": {"reads": ["diff", "evidence"], "writes": [], "commands": ["git diff"]},
    "support": {"reads": ["repo docs"], "writes": [], "commands": []},
    "human": {"reads": ["everything"], "writes": ["approval decision"], "commands": []},
}

BUG_WORDS = ["bug", "wrong", "incorrect", "error", "instead of", "expected", "crash", "fails", "failing",
             "broken", "rejected", "missing", "not applied", "regression", "exception"]
FEATURE_WORDS = ["add ", "feature", "would like", "support for", "request", "export", "ability to",
                 "new option", "enhancement"]
SUPPORT_WORDS = ["how do i", "how to", "how can i", "question", "help", "is it possible", "where can i",
                 "documentation"]
HIGH_SEVERITY = ["crash", "data loss", "security", "charged", "payment", "outage"]


# ------------------------------------------------------------------ helpers
def extract_example(body: str) -> str | None:
    """First fenced code block containing doctest-style `>>>` examples (with expected output)."""
    for block in re.findall(r"```[a-zA-Z]*\n(.*?)```", body, re.S):
        if ">>>" in block:
            return block.strip("\n") + "\n"
    return None


def prose(body: str) -> str:
    return re.sub(r"```.*?```", "", body, flags=re.S).strip()


def repo_python_files(ctx: StepContext) -> list[str]:
    files = ctx.git.out(ctx.wf["repo"], "ls-files").splitlines()
    return [f for f in files if f.endswith(".py") and not f.startswith("tests/")]


def reset_worktree(ctx: StepContext, commit: str) -> None:
    ctx.git.run(ctx.worktree, "reset", "--hard", "-q", commit)
    ctx.git.run(ctx.worktree, "clean", "-fdq")


def commit_all(ctx: StepContext, paths: list[str], message: str) -> str:
    with GIT_LOCK:
        ctx.git.run(ctx.worktree, "add", "--", *paths)
        ctx.git.run(ctx.worktree, "commit", "-q", "-m", message)
    return ctx.git.out(ctx.worktree, "rev-parse", "HEAD")


def pytest_summary(output: str) -> str:
    lines = [ln.strip() for ln in output.strip().splitlines() if ln.strip()]
    for ln in reversed(lines):
        if re.search(r"\d+ (passed|failed|error)", ln):
            return ln.strip("= ")
    return lines[-1] if lines else ""


REPRO_TEMPLATE = '''"""Reproduction test for issue #{issue_id}: {title}

Generated by System Factory (QA role) from the example in the issue report.
It must FAIL on the base commit and PASS after the fix.
"""
import doctest
import sys

EXAMPLE = {example!r}


def run_example():
    parser = doctest.DocTestParser()
    test = parser.get_doctest(EXAMPLE, {{}}, "issue_{issue_id}", "issue #{issue_id}", 0)
    runner = doctest.DocTestRunner(optionflags=doctest.NORMALIZE_WHITESPACE | doctest.ELLIPSIS)
    output = []
    result = runner.run(test, out=output.append)
    return result, "".join(output)


def test_issue_{issue_id}_reproduction():
    result, output = run_example()
    assert result.failed == 0, output


if __name__ == "__main__":
    result, output = run_example()
    print(output or "ok")
    sys.exit(1 if result.failed else 0)
'''


# ------------------------------------------------------------------ roles
def triage(ctx: StepContext) -> dict:
    wf = ctx.wf
    title, body = wf["issue_title"], wf["issue_body"]
    text = f"{title}\n{body}".lower()
    example = extract_example(body)
    scores = {
        "bug": sum(w in text for w in BUG_WORDS) + (3 if example else 0),
        "feature": sum(w in text for w in FEATURE_WORDS),
        "support": sum(w in text for w in SUPPORT_WORDS) + (1 if title.strip().endswith("?") else 0),
    }
    kind = max(["bug", "feature", "support"], key=lambda k: scores[k])  # ties: bug > feature > support
    if scores[kind] == 0:
        kind = "support"
    ranked = sorted(scores.values(), reverse=True)
    confidence = round((ranked[0] - ranked[1]) / max(ranked[0], 1), 2)
    severity = "high" if any(w in text for w in HIGH_SEVERITY) else ("low" if kind == "support" else "medium")

    components = []
    py_files = repo_python_files(ctx)
    if example:
        _, modules = repair.identifiers_in_example(example)
        components += [m.replace(".", "/") + ".py" for m in sorted(modules)]
    for f in py_files:
        stem = Path(f).stem
        if stem != "__init__" and re.search(rf"\b{re.escape(stem)}\b", text) and f not in components:
            components.append(f)
    components = [c for c in components if c in py_files]

    ctx.store.update_workflow(ctx.wf_id, kind=kind)
    ctx.log(f"Classified as {kind} (severity {severity}, confidence {confidence})", scores=scores)
    return {"kind": kind, "severity": severity, "confidence": confidence, "scores": scores,
            "components": components, "has_reproduction_example": bool(example),
            "classifier": "rule-based keyword classifier v1 (deterministic, not an LLM)"}


def requirements(ctx: StepContext) -> dict:
    wf = ctx.wf
    kind = wf["kind"]
    example = extract_example(wf["issue_body"])
    prd = {"title": wf["issue_title"], "type": kind, "problem": prose(wf["issue_body"]),
           "generator": "template PRD v1 (deterministic)"}
    if kind == "bug" and example:
        examples = doctest.DocTestParser().get_examples(example)
        prd["expected_behavior"] = [{"call": e.source.strip(), "expected": e.want.strip()}
                                    for e in examples if e.want.strip()]
        prd["acceptance_criteria"] = [
            "A reproduction test derived from the issue example fails on the base commit",
            "The same test passes after the change",
            "The full existing test suite still passes",
            "Only the source files named in the plan are modified; tests are not modified by the coding agent",
            "No security findings of high severity in the diff",
            "A human approves the change before it is merged (System Factory never merges)",
        ]
    elif kind == "bug":
        prd["acceptance_criteria"] = ["Reporter provides a runnable reproduction example"]
        prd["open_questions"] = ["No `>>>` reproduction example in the issue; cannot derive a failing test."]
    else:
        prd["user_story"] = prd["problem"].split("\n\n")[0]
        prd["acceptance_criteria"] = ["To be refined by a human or an LLM requirements agent",
                                      "New behaviour covered by new tests", "Existing suite still passes"]
        prd["open_questions"] = ["Exact output format, edge cases and error handling are unspecified."]
    ctx.evidence("prd", "Product requirements (PRD)", _render_prd(prd))
    return prd


def _render_prd(prd: dict) -> str:
    out = [f"# {prd['title']}", f"Type: {prd['type']}", "", "## Problem", prd["problem"], ""]
    if prd.get("expected_behavior"):
        out += ["## Expected behaviour"] + [f"- `{e['call']}` -> `{e['expected']}`" for e in prd["expected_behavior"]] + [""]
    out += ["## Acceptance criteria"] + [f"- {c}" for c in prd["acceptance_criteria"]]
    if prd.get("open_questions"):
        out += ["", "## Open questions"] + [f"- {q}" for q in prd["open_questions"]]
    return "\n".join(out)


def plan(ctx: StepContext) -> dict:
    wf = ctx.wf
    triage_out = wf["data"]["triage"]
    targets = triage_out["components"]
    if not targets:
        raise BlockedError("Could not locate affected source files from the issue; a human must point to the code.")
    steps = (["Create isolated git worktree on branch sf/wf-%d" % ctx.wf_id,
              "Run baseline test suite on base commit",
              "Generate reproduction test from issue example; confirm it fails; commit it",
              f"Search-based repair restricted to: {', '.join(targets)} (breadth escalates per attempt)",
              "Re-run reproduction test and full suite; capture evidence",
              "Security scan + review of the fix diff",
              "Stop and wait for human approval (no merge, no deploy)"]
             if wf["kind"] == "bug" else
             ["Create isolated git worktree", f"Implement feature in: {', '.join(targets)}",
              "Add tests", "Run suite, security scan, review", "Wait for human approval"])
    out = {"target_files": targets, "steps": steps,
           "test_strategy": "fail-before / pass-after reproduction test + full regression suite",
           "risks": ["Search-based repair can overfit a single example; the human reviewer must judge the diff."],
           "planner": "template planner v1 (deterministic)"}
    ctx.evidence("plan", "Implementation plan", "\n".join(f"{i + 1}. {s}" for i, s in enumerate(steps)))
    return out


def workspace(ctx: StepContext) -> dict:
    wf = ctx.wf
    repo = Path(wf["repo"])
    path = ctx.settings.worktrees_dir / f"wf-{ctx.wf_id}"
    branch = f"sf/wf-{ctx.wf_id}"
    base = wf.get("base_commit") or ctx.git.out(repo, "rev-parse", "HEAD")
    with GIT_LOCK:
        if (path / ".git").exists():
            ctx.log(f"Reusing existing worktree {path}")
        else:
            ctx.git.run(repo, "worktree", "prune")
            ctx.git.run(repo, "worktree", "add", "-q", "-B", branch, str(path), base)
    ctx.store.update_workflow(ctx.wf_id, branch=branch, worktree=str(path), base_commit=base)
    reset_worktree(ctx, base)
    ctx.log(f"Worktree ready at {path} on {branch} (base {base[:10]})")
    return {"worktree": str(path), "branch": branch, "base_commit": base}


def reproduce(ctx: StepContext) -> dict:
    wf = ctx.wf
    base = wf["base_commit"]
    reset_worktree(ctx, base)

    baseline = ctx.run_pytest()
    ctx.evidence("test_run", "Baseline suite on base commit", baseline.output[-4000:],
                 exit_code=baseline.exit_code, summary=pytest_summary(baseline.output), commit=base)
    if not baseline.ok:
        raise BlockedError("Baseline test suite is already failing on the base commit; "
                           "a human must fix or quarantine pre-existing failures first.")

    example = extract_example(wf["issue_body"])
    if not example:
        raise BlockedError("Issue has no `>>>` reproduction example; asked reporter for reproduction steps.")

    issue_id = wf["issue_id"]
    test_rel = f"tests/test_issue_{issue_id}.py"
    safe_title = re.sub(r"[^\w .,:()$%#-]", "", wf["issue_title"])[:100]
    ctx.workspace(["tests/test_issue_*.py"]).write_text(
        test_rel, REPRO_TEMPLATE.format(issue_id=issue_id, title=safe_title, example=example))

    res = ctx.run_pytest(test_rel)
    ctx.evidence("test_run", "Reproduction test on base commit (expected to FAIL)", res.output[-4000:],
                 exit_code=res.exit_code, summary=pytest_summary(res.output), commit=base, expected="fail")
    if res.ok:
        raise BlockedError(f"Could not reproduce: the issue example already passes on base {base[:10]}. "
                           "Needs more information from the reporter.")
    commit = commit_all(ctx, [test_rel], f"test: reproduce issue #{issue_id}\n\nGenerated by System Factory QA role.")
    ctx.log(f"Reproduced: {test_rel} fails on base; committed {commit[:10]}")
    return {"test_path": test_rel, "commit": commit, "base_failure": pytest_summary(res.output),
            "baseline": pytest_summary(baseline.output)}


def coding(ctx: StepContext) -> dict:
    wf = ctx.wf
    if wf["kind"] != "bug":
        raise BlockedError("The simulated coding runtime only performs search-based repair of bugs that have a "
                           "failing reproduction test. Implementing a feature needs an LLM coding runtime, "
                           "which is not configured. Handing off to a human developer.")
    data = wf["data"]
    checkpoint = data["reproduce"]["commit"]
    reset_worktree(ctx, checkpoint)
    targets = data["plan"]["target_files"]
    test_rel = data["reproduce"]["test_path"]
    identifiers, _ = repair.identifiers_in_example(extract_example(wf["issue_body"]) or "")
    tier = min(ctx.attempt, max(repair.TIERS))
    throttle = wf["options"].get("throttle_ms", 0) / 1000
    ws = ctx.workspace(targets)  # the coding role may write ONLY the planned source files

    def evaluate(cand: repair.Candidate) -> dict:
        ctx.charge(candidate_evals=1)
        if throttle:
            end = time.time() + throttle
            while time.time() < end:
                ctx.check_stop()
                time.sleep(0.02)
        r = ctx.run_python(test_rel, timeout=20)
        if not r.ok:
            return {"accepted": False, "repro": "fail"}
        s = ctx.run_pytest()
        return {"accepted": s.ok, "repro": "pass", "suite": "pass" if s.ok else "fail"}

    budget = wf["budget"].get("max_candidate_evals", 400) - wf["usage"].get("candidate_evals", 0)
    ctx.log(f"Attempt {ctx.attempt}: repair tier {tier} ({repair.TIERS[tier]['scope']}, "
            f"ops={repair.TIERS[tier]['ops']}) over {targets}")
    result = repair.search(ws.read_text, ws.write_text, targets, identifiers, tier, evaluate,
                           ctx.check_stop, max_evals=max(budget, 0))
    table = "\n".join(f"{t['file']} {t['candidate']}: repro={t.get('repro')} suite={t.get('suite', '-')}"
                      for t in result.tried) or "(no candidates generated)"
    ctx.evidence("repair_search", f"Attempt {ctx.attempt}: tier {tier} search, {len(result.tried)} candidates",
                 table, tier=tier, found=result.found, localisation=result.localisation)
    if not result.found:
        if result.localisation.get("budget_exhausted"):
            raise PermanentError("budget exhausted: candidate evaluation budget used up")
        raise TransientError(f"Tier {tier} search ({repair.TIERS[tier]['scope']}) evaluated "
                             f"{len(result.tried)} candidates; none passed repro + suite")
    cand = result.candidate
    diff = ctx.git.out(ctx.worktree, "diff")
    commit = commit_all(ctx, [cand.file], f"fix: {wf['issue_title']} (issue #{wf['issue_id']})\n\n"
                        f"Simulated search-based repair, tier {tier}: {cand.file} {cand.description}.")
    ctx.evidence("patch", "Proposed patch", diff, file=cand.file, mutation=cand.description)
    ctx.log(f"Patch found: {cand.file} {cand.description}; committed {commit[:10]}")
    return {"agent": "simulated search-based repair (deterministic, not an LLM)", "tier": tier,
            "file": cand.file, "mutation": cand.description, "commit": commit,
            "candidates_evaluated": len(result.tried)}


def testing(ctx: StepContext) -> dict:
    data = ctx.data
    dirty = ctx.git.out(ctx.worktree, "status", "--porcelain")
    if dirty:
        raise PermanentError(f"worktree not clean after coding: {dirty}")
    head = ctx.git.out(ctx.worktree, "rev-parse", "HEAD")
    test_rel = data["reproduce"]["test_path"]
    repro = ctx.run_pytest(test_rel)
    ctx.evidence("test_run", "Reproduction test after fix (expected to PASS)", repro.output[-4000:],
                 exit_code=repro.exit_code, summary=pytest_summary(repro.output), commit=head, expected="pass")
    suite = ctx.run_pytest()
    ctx.evidence("test_run", "Full regression suite after fix", suite.output[-4000:],
                 exit_code=suite.exit_code, summary=pytest_summary(suite.output), commit=head)
    out = {"commit": head, "repro_passed": repro.ok, "suite_passed": suite.ok,
           "repro_summary": pytest_summary(repro.output), "suite_summary": pytest_summary(suite.output),
           "base_failure": data["reproduce"]["base_failure"]}
    if not (repro.ok and suite.ok):
        raise PermanentError(f"verification failed: repro={repro.ok} suite={suite.ok}")
    return out


SECRET_PATTERNS = [
    (r"sk-ant-[A-Za-z0-9_-]{10,}", "Anthropic API key"), (r"AKIA[0-9A-Z]{16}", "AWS access key"),
    (r"-----BEGIN [A-Z ]*PRIVATE KEY-----", "private key"),
    (r"(?i)(password|passwd|secret|api_key|token)\s*=\s*['\"][^'\"]+['\"]", "hard-coded credential"),
]
DANGEROUS_CALLS = [r"\beval\(", r"\bexec\(", r"os\.system\(", r"\bsubprocess\b", r"__import__\(",
                   r"pickle\.loads?\(", r"\bshutil\.rmtree\(", r"\brequests\.|urllib\.request|socket\."]


def security(ctx: StepContext) -> dict:
    data = ctx.data
    rng = f"{data['reproduce']['commit']}..HEAD"
    files = ctx.git.out(ctx.worktree, "diff", "--name-only", rng).splitlines()
    diff = ctx.git.out(ctx.worktree, "diff", rng)
    added = [ln[1:] for ln in diff.splitlines() if ln.startswith("+") and not ln.startswith("+++")]
    removed = [ln for ln in diff.splitlines() if ln.startswith("-") and not ln.startswith("---")]
    findings = []
    targets = set(data["plan"]["target_files"])
    for f in files:
        if f.startswith("tests/"):
            findings.append({"severity": "high", "rule": "tests-modified", "detail": f"coding agent changed {f}"})
        elif f not in targets:
            findings.append({"severity": "high", "rule": "out-of-scope", "detail": f"{f} not in plan"})
    for ln in added:
        for pat, label in SECRET_PATTERNS:
            if re.search(pat, ln):
                findings.append({"severity": "high", "rule": "secret", "detail": f"{label}: {ln.strip()[:80]}"})
        for pat in DANGEROUS_CALLS:
            if re.search(pat, ln):
                findings.append({"severity": "medium", "rule": "dangerous-call", "detail": ln.strip()[:120]})
    if len(added) + len(removed) > 30:
        findings.append({"severity": "medium", "rule": "large-diff",
                         "detail": f"{len(added)}+/{len(removed)}- lines for an automated fix"})
    passed = not any(f["severity"] == "high" for f in findings)
    report = "\n".join(f"[{f['severity']}] {f['rule']}: {f['detail']}" for f in findings) or "No findings."
    ctx.evidence("security", "Security scan of fix diff", report, passed=passed, files=files)
    out = {"passed": passed, "findings": findings, "files_changed": files,
           "lines_added": len(added), "lines_removed": len(removed),
           "scanner": "static pattern + scope rules v1"}
    if not passed:
        raise PermanentError("security gate failed: " + "; ".join(f["detail"] for f in findings if f["severity"] == "high"))
    return out


def review(ctx: StepContext) -> dict:
    wf = ctx.wf
    data = wf["data"]
    if wf["kind"] == "support":
        sup = data["support"]
        checks = [{"check": "Answer drafted from repository documentation", "ok": bool(sup.get("answer"))},
                  {"check": "Answer cites its source section", "ok": bool(sup.get("source"))},
                  {"check": "Match confidence >= 0.3", "ok": sup.get("confidence", 0) >= 0.3}]
    else:
        sec, tst, cod = data["security"], data["testing"], data["coding"]
        checks = [
            {"check": "Bug reproduced: new test failed on base commit", "ok": bool(data["reproduce"]["base_failure"])},
            {"check": "Reproduction test passes after fix", "ok": tst["repro_passed"]},
            {"check": "Full regression suite passes", "ok": tst["suite_passed"]},
            {"check": "Only planned source files changed", "ok": set(sec["files_changed"]) <= set(data["plan"]["target_files"])},
            {"check": "No high-severity security findings", "ok": sec["passed"]},
            {"check": "Diff is small (<= 10 changed lines)", "ok": sec["lines_added"] + sec["lines_removed"] <= 10},
        ]
        full = ctx.git.out(ctx.worktree, "diff", f"{wf['base_commit']}..HEAD")
        ctx.evidence("diff", f"Full diff {wf['base_commit'][:10]}..{tst['commit'][:10]} (test + fix)", full)
        checks.append({"check": f"Patch: {cod['file']} {cod['mutation']}", "ok": True})
    verdict = "recommend_approve" if all(c["ok"] for c in checks) else "changes_requested"
    report = "\n".join(f"[{'PASS' if c['ok'] else 'FAIL'}] {c['check']}" for c in checks)
    report += f"\n\nVerdict: {verdict}. Final decision belongs to a human approver."
    ctx.evidence("review", "Review checklist", report, verdict=verdict)
    return {"verdict": verdict, "checks": checks, "reviewer": "rule-based review checklist v1"}


STOPWORDS = set("the a an and or to of in on for is are do does i my me how can with at it this that what "
                "when where why be by from as you your our we".split())


def support(ctx: StepContext) -> dict:
    wf = ctx.wf
    docs = Workspace(wf["repo"], writable=[])  # read-only
    try:
        readme = docs.read_text("README.md")
    except FileNotFoundError:
        raise BlockedError("Repository has no README.md to answer from; route to a human support engineer.")
    sections = re.split(r"(?m)^(?=#+ )", readme)
    words = {w for w in re.findall(r"[a-z]+", f"{wf['issue_title']} {wf['issue_body']}".lower())
             if w not in STOPWORDS and len(w) > 2}
    scored = []
    for sec in sections:
        sec_words = set(re.findall(r"[a-z]+", sec.lower()))
        scored.append((len(words & sec_words), sec.strip()))
    score, best = max(scored, key=lambda s: s[0])
    confidence = round(score / max(len(words), 1), 2)
    if score == 0:
        raise BlockedError("No documentation section matches the question; route to a human support engineer.")
    heading = best.splitlines()[0].lstrip("# ").strip()
    answer = (f"Thanks for reaching out. This is covered in the project README, section \"{heading}\":\n\n"
              f"{best}\n\nIf this does not answer your question, reply and a human engineer will follow up.")
    ctx.evidence("support_answer", "Draft support reply (not sent; needs approval)", answer,
                 source=f"README.md#{heading}", confidence=confidence)
    return {"answer": answer, "source": f"README.md#{heading}", "confidence": confidence,
            "matched_terms": sorted(words & set(re.findall(r'[a-z]+', best.lower()))),
            "responder": "documentation retrieval v1 (deterministic)"}


