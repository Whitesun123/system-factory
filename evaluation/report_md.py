"""Render evaluation/results/report.json as REPORT.md. Pure formatting: every number comes from report.json.

    python -m evaluation.report_md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "evaluation" / "results"
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from evaluation import harness  # noqa: E402


def _fmt(v: Any) -> str:
    return "–" if v is None else str(v)


def _table(rows: list[dict], labels: list[str], key: str) -> list[str]:
    out = ["| Decision source | cases | caught (TP) | false approvals | false blocks | correct approvals | "
           "escalated | errors | precision | recall |", "|---|---|---|---|---|---|---|---|---|---|"]
    for label in labels:
        rs = [{"expected_blocking": r["expected_blocking"], **r["decisions"][label]}
              for r in rows if label in r["decisions"]]
        if not rs:
            continue
        m = harness.metrics(rs, key)
        out.append(f"| `{label}` | {m['cases']} | {m['true_positives']} | {m['false_approvals']} | "
                   f"{m['false_blocks']} | {m['true_negatives']} | {m['escalations']} | {m['errors']} | "
                   f"{_fmt(m['precision'])} | {_fmt(m['recall'])} |")
    return out


def render(report: dict) -> str:
    rows, summary = report["cases"], report["summary"]
    model_labels = [c for c in report["configs"]]
    all_labels = sorted(summary)
    # cases on which every model configuration was executed: the only fair comparison set
    common = [r for r in rows if all(c in r["reviews"] for c in model_labels)]
    lines = [
        "# Reviewer evaluation report",
        "",
        "Generated by `python -m evaluation.report_md` from `report.json`; every number below is computed from "
        "recorded reviews. Labels (`evaluation/labels.json`) were written from the requirements, independent of "
        "the reviewer prompts. Models were run through **one provider** (local Ollama); different models are not "
        "different providers.",
        "",
        "## Run",
        "",
        f"- dataset cases: {report['dataset_cases']}; cases materialised: {report['executed_cases']}",
        f"- new inference: {report['new_inference_minutes']} min of a {report['budget_minutes']:.0f} min budget "
        f"(wall clock {report['wall_minutes']} min)",
        f"- (case, model) pairs **not executed** because the budget ran out: {len(report['not_executed'])}",
        f"- probes and checks executed on the `{report['execution_backend']}` backend",
        f"- Ollama {report.get('ollama_version') or 'unknown'}; peak GPU memory observed "
        f"{report.get('gpu_peak_vram_mib') or 'unknown'} MiB; cost $0 (local inference)",
        "",
        "| Configuration | model digest | prompt hash |",
        "|---|---|---|",
    ]
    for c in model_labels:
        role, model = c.split("=", 1)
        lines.append(f"| `{c}` | `{(report['model_digests'].get(model) or '')[:12]}` | "
                     f"`{report['prompt_hashes'].get(role, '')[:12]}` |")
    lines += [
        "",
        "## How to read the decisions",
        "",
        "- **raw**: the reviewer's own verdict (`request_changes` = block).",
        "- **pipeline**: what System Factory decides after executing every check and probe and classifying the "
        "evidence (ARCHITECTURE.md, evidence states). `escalated` means the evidence was unsupported, conflicting "
        "or the review did not inspect the change; the workflow goes to a human instead of approving or blocking.",
        "- A *false approval* ships a labelled defect; a *false block* rejects a correct change.",
        "",
        f"## Comparable subset: {len(common)} cases on which every configuration ran",
        "",
        "### Raw reviewer verdicts",
        "",
        *_table(common, all_labels, "raw"),
        "",
        "### Pipeline decisions (evidence-verified)",
        "",
        *_table(common, all_labels, "pipeline"),
        "",
        "## Per configuration, all cases it ran on",
        "",
        "| Configuration | cases | mean latency s | p95 s | mean input tokens | mean output tokens | "
        "valid checks | reviewer errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label in all_labels:
        e = summary[label]
        if "latency_s" not in e:
            continue
        lines.append(f"| `{label}` | {e['pipeline']['cases']} | {e['latency_s']['mean']} | {e['latency_s']['p95']} | "
                     f"{e['tokens']['input_mean']} | {e['tokens']['output_mean']} | "
                     f"{_fmt(e.get('check_validity_rate'))} | {e.get('errors', 0)} |")
    lines += ["", "## Per case", "", "| Case | category | expected | " +
              " | ".join(f"`{c}`" for c in model_labels) + " |",
              "|---|---|---|" + "---|" * len(model_labels)]
    for r in rows:
        cells = []
        for c in model_labels:
            d = r["decisions"].get(c)
            cells.append("not run" if d is None else f"{d['raw']} → {d['pipeline']}")
        lines.append(f"| {r['case']} | {r['category']} | {'block' if r['expected_blocking'] else 'approve'} | "
                     + " | ".join(cells) + " |")
    errors = [(r["case"], c, r["reviews"][c].get("error")) for r in rows for c in model_labels
              if c in r["reviews"] and r["reviews"][c].get("verdict") == "error"]
    if errors:
        lines += ["", "## Reviewer errors (recorded, never counted as approvals)", ""]
        lines += [f"- {case} / `{c}`: {err}" for case, c, err in errors]
    if report["not_executed"]:
        lines += ["", "## Not executed (budget)", ""]
        by_cfg: dict[str, list[str]] = {}
        for x in report["not_executed"]:
            by_cfg.setdefault(x["config"], []).append(x["case"])
        lines += [f"- `{c}`: {', '.join(cs)}" for c, cs in by_cfg.items()]
    return "\n".join(lines) + "\n"


def main() -> int:
    report = json.loads((RESULTS / "report.json").read_text(encoding="utf-8"))
    (RESULTS / "REPORT.md").write_text(render(report), encoding="utf-8", newline="\n")
    print(RESULTS / "REPORT.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
